-- Drop the redundant duplicate GIN index on products.
--
-- Context: The init migration (20260613020117_init) creates products_norm_name_trgm.
-- The fix migration (20260613023739_fix_immutable_unaccent) drops and recreates
-- products_name_norm_gin (which did not yet exist at init time, so the DROP in the
-- fix migration was a no-op on fresh deploys). Result: both indexes survived a
-- from-scratch deploy with identical expressions — wasting ~30 MB of index space
-- and doubling write maintenance cost on the products table.
--
-- Resolution: keep products_name_norm_gin (the authoritative, correctly-named index
-- from the fix migration) and drop products_norm_name_trgm (the stale init index).
-- IF NOT EXISTS makes this idempotent — safe on databases where this index was
-- already removed (dev/test already had it removed by migration 20260613000945).
DROP INDEX IF EXISTS "products_norm_name_trgm";
